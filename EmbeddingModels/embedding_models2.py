# Commented out IPython magic to ensure Python compatibility.
# %pip install -q langchain-huggingface sentence-transformers

from langchain_huggingface  import HuggingFaceEmbeddings

embeddings=HuggingFaceEmbeddings(
    model_name="sentence-transformers/all-MiniLM-L6-v2"
)

docs=[
    'Virat Kohli is an Indian cricketer',
    'Rohit Sharma is an Indian cricketer',
    'Sachin Tendulkar is an Indian cricketer'
]

query ='tell me about Virat Kohli'

queryem=embeddings.embed_query(query)
docsemb=embeddings.embed_documents(docs)

print(queryem[:5])

from sklearn.metrics.pairwise import cosine_similarity
import numpy as np

score=cosine_similarity([queryem],docsemb)[0]
print(score)

index,ans=sorted(list(enumerate(score)),key=lambda x:x[1])[-1]

print(query)
print(docs[index])
print('Similarity Score is:',ans)